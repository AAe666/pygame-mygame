# ---------- 数值表（动态生成）----------
def hp_table_for(difficulty):
    """返回指定难度的 (波次, 怪物血, 小宝箱, 大宝箱, BOSS, 怪物数量) 列表。"""
    p = S.DIFFICULTY_PARAMS[difficulty]
    rows = []
    for w in range(1, p["waves"] + 1):
        mhp = _hp_with(w, p["lin"], p["quad"])
        rows.append((w, mhp, mhp * 5, mhp * 12, mhp * p["boss_mult"],
                     S.monster_count(w)))
    return rows


def _hp_with(wave, lin, quad):
    d = wave - 1
    base = S.MONSTER_HP_BASE + d + d * d
    scale = 1.0 + lin * d + quad * d * d
    return int(round(base * scale))


def all_difficulty_hp_rows():
    """返回 [(波次, 简单, 普通, 困难, 噩梦)] 列表，用于四难度并列血量表。"""
    max_w = max(S.DIFFICULTY_PARAMS[d]["waves"] for d in S.DIFFICULTY_ORDER)
    rows = []
    for w in range(1, max_w + 1):
        vals = []
        for d in S.DIFFICULTY_ORDER:
            p = S.DIFFICULTY_PARAMS[d]
            if w <= p["waves"]:
                vals.append(_hp_with(w, p["lin"], p["quad"]))
            else:
                vals.append(None)
        rows.append((w,) + tuple(vals))
    return rows
